    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")

    // Text recognition ships one model per script. The plugin bundles Latin
    // and declares the rest `compileOnly`, so without these the classes are
    // referenced but absent: R8 fails the release build, and at runtime any
    // script but Latin is unreadable. Each model is a few megabytes, which is
    // the price of reading a page that is not written in a Latin alphabet.
    //
    // `api/script.rs` decides which of them to believe; Android only runs them.
